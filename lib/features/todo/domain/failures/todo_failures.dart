import 'package:todo/core/errors/failures.dart';

/// Failures the todo feature can produce.
///
/// Sealed so that presentation code can switch over them exhaustively. Every
/// concrete type describes exactly one reason, because the UI turns failures
/// into display messages based on their type (see `lib/features/AGENTS.md`);
/// [message] stays diagnostic and is never shown verbatim.
sealed class TodoFailure extends Failure {
  const TodoFailure({required super.message});
}

/// The content of a todo is empty or only whitespace.
final class TodoContentEmptyFailure extends TodoFailure {
  const TodoContentEmptyFailure() : super(message: '待办内容为空');
}

/// The content of a todo is longer than the domain accepts.
final class TodoContentTooLongFailure extends TodoFailure {
  const TodoContentTooLongFailure({required this.maxLength})
    : super(message: '待办内容超过 $maxLength 个字符');

  /// Limit that was exceeded.
  final int maxLength;
}

/// An identifier was built from an empty or whitespace-only value.
///
/// Unlike the content failures this one is not caused by user input:
/// identifiers are generated by the repository, so the presentation layer
/// answers it with a generic message instead of exposing the detail.
final class TodoIdEmptyFailure extends TodoFailure {
  const TodoIdEmptyFailure() : super(message: '待办 id 为空');
}

/// A todo was asked to complete although it was completed already.
///
/// Exists because completion is a one-off transition: repeating it means the
/// caller acted on a stale state, which is a business error rather than a
/// harmless no-op.
final class TodoAlreadyCompletedFailure extends TodoFailure {
  const TodoAlreadyCompletedFailure() : super(message: '待办已完成，无法重复完成');
}

/// A todo was addressed by an identifier the local cache does not hold.
///
/// The list only ever shows persisted todos, so this means the caller acted on
/// a stale reference (the row disappeared between render and tap).
final class TodoNotFoundFailure extends TodoFailure {
  const TodoNotFoundFailure() : super(message: '待办不存在或已被移除');
}

/// Reading the locally cached todos failed.
final class TodoLoadFailure extends TodoFailure {
  const TodoLoadFailure({required super.message});
}

/// Persisting a todo into the local cache failed.
final class TodoSaveFailure extends TodoFailure {
  const TodoSaveFailure({required super.message});
}
